  static int _bit(List<int> bytes, int source, int target) =>
      ((bytes[(source ~/ 32) * 4 + 3 - (source % 32) ~/ 8] >>
              (7 - source % 8)) &
          1) <<
      target;
  static int _fromInt(int value, int source, int target) =>
      ((value >> (31 - source)) & 1) << target;
  static int _leftBit(int value, int source, int target) =>
      ((value << source) & 0x80000000) >> target;
  static int _boxIndex(int value) =>
      (value & 32) | ((value & 31) >> 1) | ((value & 1) << 4);

  static List<List<int>> _schedule(List<int> key, bool decrypt) {
    var c = 0;
    var d = 0;
    for (var i = 0; i < 28; i++) {
      c |= _bit(key, _keyC[i], 31 - i);
      d |= _bit(key, _keyD[i], 31 - i);
    }
    final result = List.generate(16, (_) => List<int>.filled(6, 0));
    for (var i = 0; i < 16; i++) {
      c = ((c << _shifts[i]) | (c >> (28 - _shifts[i]))) & 0xfffffff0;
      d = ((d << _shifts[i]) | (d >> (28 - _shifts[i]))) & 0xfffffff0;
      final row = result[decrypt ? 15 - i : i];
      for (var j = 0; j < 24; j++) {
        row[j ~/ 8] |= _fromInt(c, _compression[j], 7 - j % 8);
      }
      for (var j = 24; j < 48; j++) {
        row[j ~/ 8] |= _fromInt(d, _compression[j] - 27, 7 - j % 8);
      }
    }
    return result;
  }

  static int _f(int state, List<int> key) {
    final t1 =
        _leftBit(state, 31, 0) |
        ((state & 0xf0000000) >> 1) |
        _leftBit(state, 4, 5) |
        _leftBit(state, 3, 6) |
        ((state & 0x0f000000) >> 3) |
        _leftBit(state, 8, 11) |
        _leftBit(state, 7, 12) |
        ((state & 0x00f00000) >> 5) |
        _leftBit(state, 12, 17) |
        _leftBit(state, 11, 18) |
        ((state & 0x000f0000) >> 7) |
        _leftBit(state, 16, 23);
    final t2 =
        _leftBit(state, 15, 0) |
        ((state & 0x0000f000) << 15) |
        _leftBit(state, 20, 5) |
        _leftBit(state, 19, 6) |
        ((state & 0x00000f00) << 13) |
        _leftBit(state, 24, 11) |
        _leftBit(state, 23, 12) |
        ((state & 0x000000f0) << 11) |
        _leftBit(state, 28, 17) |
        _leftBit(state, 27, 18) |
        ((state & 0x0000000f) << 9) |
        _leftBit(state, 0, 23);
    final expanded = [
      ((t1 >> 24) & 255) ^ key[0],
      ((t1 >> 16) & 255) ^ key[1],
      ((t1 >> 8) & 255) ^ key[2],
      ((t2 >> 24) & 255) ^ key[3],
      ((t2 >> 16) & 255) ^ key[4],
      ((t2 >> 8) & 255) ^ key[5],
    ];
    final substituted =
        (_boxes[0][_boxIndex(expanded[0] >> 2)] << 28) |
        (_boxes[1][_boxIndex(((expanded[0] & 3) << 4) | (expanded[1] >> 4))] <<
            24) |
        (_boxes[2][_boxIndex(((expanded[1] & 15) << 2) | (expanded[2] >> 6))] <<
            20) |
        (_boxes[3][_boxIndex(expanded[2] & 63)] << 16) |
        (_boxes[4][_boxIndex(expanded[3] >> 2)] << 12) |
        (_boxes[5][_boxIndex(((expanded[3] & 3) << 4) | (expanded[4] >> 4))] <<
            8) |
        (_boxes[6][_boxIndex(((expanded[4] & 15) << 2) | (expanded[5] >> 6))] <<
            4) |
        _boxes[7][_boxIndex(expanded[5] & 63)];
    var result = 0;
    for (var i = 0; i < 32; i++) {
      result |= _leftBit(substituted, _p[i], i);
    }
    return result & 0xffffffff;
  }

  static Uint8List _crypt(List<int> input, List<List<int>> schedule) {
    final state = List<int>.filled(2, 0);
    for (var half = 0; half < 2; half++) {
      for (var i = 0; i < 32; i++) {
        state[half] |= _bit(input, _ip[half][i], 31 - i);
      }
    }
    for (var i = 0; i < 15; i++) {
      final right = state[1];
      state[1] = (_f(right, schedule[i]) ^ state[0]) & 0xffffffff;
      state[0] = right;
    }
    state[0] = (_f(state[1], schedule[15]) ^ state[0]) & 0xffffffff;
    final output = Uint8List(8);
    for (var byte = 0; byte < 8; byte++) {
      for (var bit = 0; bit < 8; bit++) {
        final ref = _inverse[byte][bit];
        output[byte] |= _fromInt(state[ref[0]], ref[1], 7 - bit);
      }
    }
    return output;
  }

  static String decodeHex(String hex) {
    if (hex.isEmpty ||
        hex.length.isOdd ||
        hex.length > 2000000 ||
        !RegExp(r'^[0-9a-fA-F]+$').hasMatch(hex)) {
      throw const FormatException('Invalid QRC ciphertext');
    }
    final encrypted = Uint8List.fromList([
      for (var i = 0; i < hex.length; i += 2)
        int.parse(hex.substring(i, i + 2), radix: 16),
    ]);
    if (encrypted.length % 8 != 0) {
      throw const FormatException('Invalid QRC block size');
    }
    final key = ascii.encode(_keyText);
    final stages = [
      _schedule(key.sublist(16), true),
      _schedule(key.sublist(8), false),
      _schedule(key.sublist(0), true),
    ];
    final decoded = BytesBuilder(copy: false);
    for (var i = 0; i < encrypted.length; i += 8) {
      var block = Uint8List.fromList(encrypted.sublist(i, i + 8));
      for (final schedule in stages) {
        block = _crypt(block, schedule);
      }
      decoded.add(block);
    }
    return utf8.decode(ZLibDecoder().convert(decoded.takeBytes()));
  }
